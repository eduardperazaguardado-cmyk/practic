# 1. Bloque de texto de 3 líneas
texto = """Gente, hay que empezar a preocuparnos menos y a disfrutar más
 porque la vida va rápido, demasiado rápido,
 asi como este año que me lo llevo en el corazon por siempre"""

# 2. Contar cuántas veces aparece la letra "a"
